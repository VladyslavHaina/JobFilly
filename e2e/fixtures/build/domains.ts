import { createHash } from "node:crypto";
import type { DomainsFile } from "../../rdap/domains.ts";

// The domain fixtures of MVP 2 (F5): the sender check reads a domain's age from RDAP and its MX
// records from DNS, which the test stack serves without the internet: the fake RDAP service
// (e2e/rdap/domains.json) and CoreDNS (e2e/dns/zones). Every sender domain of the fixtures gets
// a registration age and an MX record. Domains are years old, except the two scams' young ones.

/** Domains whose age is part of the ground truth: the scams' (MVP 1's backlog one, MVP 2's). */
const YOUNG_DOMAINS: Record<string, number> = {
  "globalcareers-mail.example": 40,
  "quickhire-global.example": 6,
};

/** A stable age between 4 and 20 years from the domain's name. */
function ageOf(domain: string): number {
  const n = createHash("sha256").update(domain).digest().readUInt32BE(0);
  return 1500 + (n % 5800);
}

export function domainsFile(senderDomains: Iterable<string>): DomainsFile {
  const domains: DomainsFile["domains"] = {};
  for (const d of [...new Set(senderDomains)].sort()) {
    domains[d] = { registeredDaysAgo: YOUNG_DOMAINS[d] ?? ageOf(d) };
  }
  return { domains };
}

/** The zone the test stack may own whole: .example is reserved (RFC 2606), nobody else's. */
const OWNED_ZONE = "example";

function isOwned(domain: string): boolean {
  return domain.endsWith(`.${OWNED_ZONE}`);
}

/** The address every mail host of the fixtures resolves to (TEST-NET-1, RFC 5737). */
const MAIL_HOST_ADDRESS = "192.0.2.25";
const NAME_SERVER_ADDRESS = "192.0.2.53";

/**
 * e2e/dns/zones/db.example, by its path relative to e2e/dns: the .example sender domains' MX
 * records. Public domains (gmail.com, linkedin.com, ...) get no zone file: CoreDNS would then be
 * authoritative for every name under them, and imap.gmail.com or smtp.gmail.com would get
 * NXDOMAIN inside the stack. The Corefile answers them by exact name instead (corefile).
 */
export function zoneFiles(senderDomains: Iterable<string>): Map<string, string> {
  const zone = OWNED_ZONE;
  const domains = [...new Set(senderDomains)].filter(isOwned).sort();
  const files = new Map<string, string>();
  if (domains.length === 0) return files;
  const owner = (name: string) => name.slice(0, -(zone.length + 1));
  const lines = [
    "; Generated by e2e/fixtures/build from the fixtures' sender domains: edit the sources and",
    "; run node e2e/fixtures/build/main.ts. Every sender domain has an MX record (F5).",
    `$ORIGIN ${zone}.`,
    "$TTL 300",
    `@ IN SOA ns.${zone}. hostmaster.${zone}. 1 3600 600 86400 300`,
    `@ IN NS ns.${zone}.`,
    `ns IN A ${NAME_SERVER_ADDRESS}`,
  ];
  for (const d of domains) {
    lines.push(`${owner(d)} IN MX 10 mx.${d}.`, `${owner(`mx.${d}`)} IN A ${MAIL_HOST_ADDRESS}`);
  }
  files.set(`zones/db.${zone}`, `${lines.join("\n")}\n`);
  return files;
}

/** An anchored regex for exactly one name, written with [.] so the Corefile needs no escapes. */
function exactName(name: string): string {
  return `^${name.split(".").join("[.]")}[.]$`;
}

/**
 * e2e/dns/Corefile, by its path relative to e2e/dns. The .example zone is loaded from /zones. A
 * public sender domain's MX record, and its mail host's address, are answered by the template
 * plugin for those exact names only; every other name falls through to Docker's resolver, so the
 * real imap.gmail.com and smtp.gmail.com still resolve in the stack.
 */
export function corefile(senderDomains: Iterable<string>): Map<string, string> {
  const pub = [...new Set(senderDomains)].filter((d) => !isOwned(d)).sort();
  const template = (type: string, names: string[], answer: string) => [
    `    template IN ${type} {`,
    ...names.map((n) => `        match "${exactName(n)}"`),
    `        answer "${answer}"`,
    "        fallthrough",
    "    }",
  ];
  const lines = [
    "# Generated by e2e/fixtures/build from the fixtures' sender domains: edit the sources and run",
    "# node e2e/fixtures/build/main.ts. The test stack's DNS server (docker/compose.e2e.yaml,",
    "# service dns): CoreDNS answering for the fixtures' sender domains, so the sender check's MX",
    "# lookups run for real without the internet (MVP 2, F5). The .example zone comes from /zones;",
    "# a public domain's MX and mail host are answered by exact name, never as a whole zone. Every",
    "# other name is forwarded to Docker's resolver, which also knows the stack's services.",
    ". {",
    "    auto {",
    "        directory /zones",
    "    }",
    ...(pub.length === 0
      ? []
      : [
          ...template("MX", pub, "{{ .Name }} 300 IN MX 10 mx.{{ .Name }}"),
          ...template(
            "A",
            pub.map((d) => `mx.${d}`),
            `{{ .Name }} 300 IN A ${MAIL_HOST_ADDRESS}`,
          ),
        ]),
    "    forward . /etc/resolv.conf",
    "    errors",
    "    log",
    "}",
  ];
  return new Map([["Corefile", `${lines.join("\n")}\n`]]);
}
