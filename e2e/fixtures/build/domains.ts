import { createHash } from "node:crypto";
import type { DomainsFile } from "../../rdap/domains.ts";

// The domain fixtures of MVP 2 (F5): the sender check reads a domain's age from RDAP and its MX
// records from DNS, which the test stack serves without the internet: the fake RDAP service
// (e2e/rdap/domains.json) and CoreDNS (e2e/dns/zones). Every sender domain of the fixtures gets
// a registration age and an MX record. Domains are years old, except the two scams' young ones.

/** Domains whose age is part of the ground truth: the scams' (MVP 1's backlog one, MVP 2's). */
const YOUNG_DOMAINS: Record<string, number> = {
  "globalcareers-mail.example": 40,
  "quickhire-global.example": 6,
};

/** A stable age between 4 and 20 years from the domain's name. */
function ageOf(domain: string): number {
  const n = createHash("sha256").update(domain).digest().readUInt32BE(0);
  return 1500 + (n % 5800);
}

export function domainsFile(senderDomains: Iterable<string>): DomainsFile {
  const domains: DomainsFile["domains"] = {};
  for (const d of [...new Set(senderDomains)].sort()) {
    domains[d] = { registeredDaysAgo: YOUNG_DOMAINS[d] ?? ageOf(d) };
  }
  return { domains };
}

/**
 * The CoreDNS zone a sender domain is served from: "example" for every .example domain (RFC
 * 2606), otherwise its last two labels (jobs.nhs.uk → nhs.uk, hire.lever.co → lever.co).
 */
function zoneOf(domain: string): string {
  if (domain.endsWith(".example")) return "example";
  return domain.split(".").slice(-2).join(".");
}

/** The address every mail host of the fixtures resolves to (TEST-NET-1, RFC 5737). */
const MAIL_HOST_ADDRESS = "192.0.2.25";
const NAME_SERVER_ADDRESS = "192.0.2.53";

/** e2e/dns/zones/db.<zone> for every zone, by its path relative to e2e/dns. */
export function zoneFiles(senderDomains: Iterable<string>): Map<string, string> {
  const byZone = new Map<string, string[]>();
  for (const d of [...new Set(senderDomains)].sort()) {
    const zone = zoneOf(d);
    byZone.set(zone, [...(byZone.get(zone) ?? []), d]);
  }
  const files = new Map<string, string>();
  for (const [zone, domains] of [...byZone].sort(([a], [b]) => (a < b ? -1 : 1))) {
    const owner = (name: string) => (name === zone ? "@" : name.slice(0, -(zone.length + 1)));
    const lines = [
      "; Generated by e2e/fixtures/build from the fixtures' sender domains: edit the sources and",
      "; run node e2e/fixtures/build/main.ts. Every sender domain has an MX record (F5).",
      `$ORIGIN ${zone}.`,
      "$TTL 300",
      `@ IN SOA ns.${zone}. hostmaster.${zone}. 1 3600 600 86400 300`,
      `@ IN NS ns.${zone}.`,
      `ns IN A ${NAME_SERVER_ADDRESS}`,
    ];
    for (const d of domains) {
      lines.push(`${owner(d)} IN MX 10 mx.${d}.`, `${owner(`mx.${d}`)} IN A ${MAIL_HOST_ADDRESS}`);
    }
    files.set(`zones/db.${zone}`, `${lines.join("\n")}\n`);
  }
  return files;
}
